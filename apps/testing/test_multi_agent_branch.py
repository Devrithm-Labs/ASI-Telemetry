import os
import sys
import time

SDK_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "app-sdk", "src"))
if SDK_PATH not in sys.path:
    sys.path.insert(0, SDK_PATH)

from asi_telemetry import traceable, create_trace_context, set_agent_info

def run_simulation():
    # -------------------------------------------------------------------------
    # 1. Agent A Execution Flow
    # -------------------------------------------------------------------------
    set_agent_info(agent_name="Agent A", agent_address="agent1q_agent_a_address_xyz")

    @traceable(name="validate_payload", run_type="tool")
    def validate_payload(data: dict):
        time.sleep(0.01)
        return {"valid": True}

    @traceable(name="fetch_auth_token", run_type="tool")
    def fetch_auth_token():
        time.sleep(0.015)
        return "Bearer sample_token_123"

    @traceable(name="send_request", run_type="tool")
    def send_request(prompt: str):
        # Child 1 under Agent A
        validate_payload({"prompt": prompt})
        # Child 2 under Agent A
        token = fetch_auth_token()
        # Create distributed context to pass across network to Agent B
        ctx = create_trace_context()
        return {"prompt": prompt, "token": token, "trace_context": ctx}

    print("[1] Executing Agent A starting point...")
    agent_a_msg = send_request("Analyze network telemetry anomalies")
    print(f"    Trace Context generated by Agent A: {agent_a_msg['trace_context']}")

    # -------------------------------------------------------------------------
    # 2. Agent B Execution Flow (simulating receipt across network)
    # -------------------------------------------------------------------------
    set_agent_info(agent_name="Agent B", agent_address="agent1q_agent_b_address_uvw")

    @traceable(name="query_vector_db", run_type="tool")
    def query_vector_db(query: str):
        time.sleep(0.02)
        return [{"id": "doc_1", "score": 0.98}]

    @traceable(name="generate_llm_response", run_type="llm")
    def generate_llm_response(context_data: list):
        time.sleep(0.05)
        return "No network anomalies detected across all monitoring clusters."

    @traceable(name="handle_request", run_type="tool")
    def handle_request(msg: dict):
        # Child 1 under Agent B
        docs = query_vector_db(msg.get("prompt", ""))
        # Child 2 under Agent B
        reply = generate_llm_response(docs)
        return reply

    print("\n[2] Executing Agent B starting point (with incoming trace_context)...")
    reply = handle_request(agent_a_msg)
    print(f"    Agent B Reply: {reply}")
    
    # Wait for daemon thread HTTP dispatches to complete
    time.sleep(1.0)
    print("\nSimulation complete! Traces dispatched.")

if __name__ == "__main__":
    run_simulation()
